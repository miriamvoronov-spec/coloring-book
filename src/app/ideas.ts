export const IDEA_CATEGORIES = Object.keys(POOL);

/** All combinations: 6 categories × 12 subjects × 6 twists = 432 ideas. */
export function allIdeas(): string[] {
  const out: string[] = [];
  for (const { subjects, twists } of Object.values(POOL)) for (const s of subjects) for (const t of twists) out.push(`${s} ${t}`);
  return out;
}

export function surprise(category?: string): string {
  const cats = category && POOL[category] ? [category] : IDEA_CATEGORIES;
  const c = POOL[cats[Math.floor(Math.random() * cats.length)]];
  return `${c.subjects[Math.floor(Math.random() * c.subjects.length)]} ${c.twists[Math.floor(Math.random() * c.twists.length)]}`;
}

