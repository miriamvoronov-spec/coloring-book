const pick = <T,>(a: T[]): T => a[Math.floor(Math.random() * a.length)];
export const IDEA_CATEGORIES = Object.keys(PAGE_POOL);
const recent: string[] = [];

/** A page idea from the local pool, never one of the last dozen shown. */
export function surprise(category?: string): string {
  const pool = category && PAGE_POOL[category] ? PAGE_POOL[category] : Object.values(PAGE_POOL).flat();
  let idea = pick(pool);
  for (let i = 0; i < 20 && recent.includes(idea); i++) idea = pick(pool);
  recent.push(idea); if (recent.length > 12) recent.shift();
  return idea;
}

export function surpriseTheme(): string {
  let t = pick(THEME_POOL);
  for (let i = 0; i < 20 && recent.includes(t); i++) t = pick(THEME_POOL);
  recent.push(t); if (recent.length > 12) recent.shift();
  return t;
}

type Sample = (input: string, opts?: { signal?: AbortSignal; modelTier?: string; cache?: boolean }) => Promise<{ text: string }>;

/**
 * Several fresh ideas. With Claude available they are newly invented; offline,
 * or if anything goes wrong, they come from the pool above.
 */
export async function freshIdeas(kind: 'page' | 'theme', n: number, avoid: string[] = [], signal?: AbortSignal): Promise<string[]> {
  const local = () => Array.from({ length: n }, () => (kind === 'page' ? surprise() : surpriseTheme()));
  try {
    const s = await useCap<Sample>('sample');
    if (!s) return local();
    const examples = (kind === 'page' ? Object.values(PAGE_POOL).flat() : THEME_POOL).sort(() => Math.random() - 0.5).slice(0, 6);
    const what = kind === 'page'
      ? 'ideas for a single color-by-number page. Each is one vivid Hebrew sentence of 8 to 16 words: a clear main subject, a small story moment, and a setting with plenty of shapes to color.'
      : 'themes for a whole coloring book. Each is a short, playful Hebrew phrase of 3 to 8 words: a cast of characters in a surprising role or world, so every page can be a variation.';
    const prompt = `Invent ${n} original ${what}
Style: warm, magical, whimsical, suitable for an adult who loves fairy tales. Mix different worlds (nature, animals, fairy tales, sweets, home, sea, space, seasons). No famous brands or copyrighted characters.
Examples of the style (do not repeat them): ${examples.map((e) => `"${e}"`).join(', ')}
Do not use any of these either: ${avoid.slice(0, 20).map((e) => `"${e}"`).join(', ') || 'none'}
Answer with JSON only: an array of ${n} Hebrew strings.`;
    const { text } = await s(prompt, { signal, modelTier: 'quick', cache: false });
    const m = text.match(/\[[\s\S]*\]/);
    const arr = m ? (JSON.parse(m[0]) as unknown[]).map((x) => String(x).trim()).filter((x) => x && /[א-ת]/.test(x)) : [];
    return arr.length ? arr.slice(0, n) : local();
  } catch (e) {
    if ((e as Error)?.name === 'AbortError') throw e;
    return local();
  }
}
